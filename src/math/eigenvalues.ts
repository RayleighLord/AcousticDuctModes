/** Runtime-checked table access retained even though public indices are typed. */
export function besselDerivativeRoot(m: ModeIndex, n: ModeIndex): number {
  const value = BESSEL_DERIVATIVE_ROOTS[m]?.[n];
  if (value === undefined) {
    throw new RangeError(`No derivative root is available for mode (${m}, ${n}).`);
  }
  return value;
}

export function radialEigenvalue(mode: ModeSelection): number;
export function radialEigenvalue(m: ModeIndex, n: ModeIndex): number;
export function radialEigenvalue(
  modeOrM: ModeSelection | ModeIndex,
  maybeN?: ModeIndex,
): number {
  const mode = typeof modeOrM === "number"
    ? createModeSelection(modeOrM, maybeN)
    : createModeSelection(modeOrM.m, modeOrM.n);

  return besselDerivativeRoot(mode.m, mode.n);
}
